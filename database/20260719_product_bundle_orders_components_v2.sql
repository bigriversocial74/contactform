  CONSTRAINT fk_gift_bundle_order_components_version FOREIGN KEY (product_version_id) REFERENCES catalog_product_versions(id),
  CONSTRAINT fk_gift_bundle_order_components_commerce_item FOREIGN KEY (commerce_order_item_id) REFERENCES commerce_order_items(id),
  CONSTRAINT fk_gift_bundle_order_components_pppm_request FOREIGN KEY (pppm_issuance_request_id) REFERENCES pppm_issuance_requests(id),
  CONSTRAINT fk_gift_bundle_order_components_pppm_item FOREIGN KEY (pppm_item_id) REFERENCES pppm_items(id),
  CONSTRAINT fk_gift_bundle_order_components_microgift FOREIGN KEY (microgift_instance_id) REFERENCES microgift_instances(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS gift_bundle_inventory_reservations (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  public_id CHAR(36) NOT NULL,
  bundle_order_id BIGINT UNSIGNED NOT NULL,
  bundle_component_id BIGINT UNSIGNED NOT NULL,
  quantity INT UNSIGNED NOT NULL,
  reservation_status ENUM('active','committed','released','expired','cancelled') NOT NULL DEFAULT 'active',
  idempotency_key VARCHAR(190) NOT NULL,
  expires_at DATETIME NULL,
  committed_at DATETIME NULL,
  released_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_gift_bundle_inventory_public_id (public_id),
  UNIQUE KEY uq_gift_bundle_inventory_idempotency (idempotency_key),
  KEY idx_gift_bundle_inventory_component_status (bundle_component_id,reservation_status,expires_at),
  CONSTRAINT fk_gift_bundle_inventory_order FOREIGN KEY (bundle_order_id) REFERENCES gift_bundle_orders(id) ON DELETE CASCADE,
  CONSTRAINT fk_gift_bundle_inventory_component FOREIGN KEY (bundle_component_id) REFERENCES gift_bundle_components(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

