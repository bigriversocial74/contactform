  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  public_id CHAR(36) NOT NULL,
  bundle_order_id BIGINT UNSIGNED NOT NULL,
  component_id BIGINT UNSIGNED NULL,
  actor_user_id BIGINT UNSIGNED NULL,
  event_type VARCHAR(100) NOT NULL,
  idempotency_key VARCHAR(190) NULL,
  event_data JSON NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_gift_bundle_order_events_public_id (public_id),
  UNIQUE KEY uq_gift_bundle_order_events_idempotency (idempotency_key),
  KEY idx_gift_bundle_order_events_order_created (bundle_order_id,created_at),
  CONSTRAINT fk_gift_bundle_order_events_order FOREIGN KEY (bundle_order_id) REFERENCES gift_bundle_orders(id) ON DELETE CASCADE,
  CONSTRAINT fk_gift_bundle_order_events_component FOREIGN KEY (component_id) REFERENCES gift_bundle_order_components(id) ON DELETE CASCADE,
  CONSTRAINT fk_gift_bundle_order_events_actor FOREIGN KEY (actor_user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

