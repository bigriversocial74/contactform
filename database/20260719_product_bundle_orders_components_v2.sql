CREATE TABLE IF NOT EXISTS gift_bundle_orders (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  public_id CHAR(36) NOT NULL,
  bundle_id BIGINT UNSIGNED NOT NULL,
  bundle_terms_version INT UNSIGNED NOT NULL,
  buyer_user_id BIGINT UNSIGNED NOT NULL,
  recipient_user_id BIGINT UNSIGNED NULL,
  recipient_name VARCHAR(190) NULL,
  recipient_email VARCHAR(255) NULL,
  commerce_order_id BIGINT UNSIGNED NULL,
  order_status ENUM('draft','reserved','awaiting_payment','paid','fulfillment_pending','partially_issued','issued','cancelled','refunded','partially_refunded') NOT NULL DEFAULT 'draft',
  payment_status ENUM('unpaid','pending','paid','failed','cancelled','partially_refunded','refunded') NOT NULL DEFAULT 'unpaid',
  fulfillment_status ENUM('pending','partial','issued','failed','cancelled') NOT NULL DEFAULT 'pending',
  currency CHAR(3) NOT NULL DEFAULT 'USD',
  subtotal_cents BIGINT UNSIGNED NOT NULL,
  platform_fee_cents BIGINT UNSIGNED NOT NULL DEFAULT 0,
  total_cents BIGINT UNSIGNED NOT NULL,
  fixed_platform_fee_cents BIGINT UNSIGNED NOT NULL DEFAULT 0,
  component_count INT UNSIGNED NOT NULL,
  bundle_snapshot_json JSON NOT NULL,
  commission_snapshot_json JSON NOT NULL,
  campaign_attribution_json JSON NULL,
  idempotency_key VARCHAR(190) NOT NULL,
  reserved_at DATETIME NULL,
  paid_at DATETIME NULL,
  issued_at DATETIME NULL,
  cancelled_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_gift_bundle_orders_public_id (public_id),
  UNIQUE KEY uq_gift_bundle_orders_idempotency (idempotency_key),
  KEY idx_gift_bundle_orders_buyer_status (buyer_user_id,order_status,created_at),
  KEY idx_gift_bundle_orders_bundle_status (bundle_id,order_status,created_at),
  KEY idx_gift_bundle_orders_commerce_order (commerce_order_id),
  CONSTRAINT fk_gift_bundle_orders_bundle FOREIGN KEY (bundle_id) REFERENCES gift_bundles(id),
  CONSTRAINT fk_gift_bundle_orders_buyer FOREIGN KEY (buyer_user_id) REFERENCES users(id),
  CONSTRAINT fk_gift_bundle_orders_recipient FOREIGN KEY (recipient_user_id) REFERENCES users(id),
  CONSTRAINT fk_gift_bundle_orders_commerce FOREIGN KEY (commerce_order_id) REFERENCES commerce_orders(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

